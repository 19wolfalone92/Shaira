"""Build the offline Russian audio banks from the curriculum and the Piper Denis model."""

import argparse
from base64 import b64encode
import json
import os
from pathlib import Path
import subprocess
import tempfile
import wave

ROOT = Path(__file__).resolve().parents[1]
LETTERS = dict(zip("АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ", (
    "а", "бэ", "вэ", "гэ", "дэ", "йэ", "йо", "жэ", "зэ", "и", "и краткое", "ка",
    "эль", "эм", "эн", "о", "пэ", "эр", "эс", "тэ", "у", "эф", "ха", "цэ",
    "че", "ша", "ща", "твёрдый знак", "ы", "мягкий знак", "э", "ю", "я",
), strict=True))

def write_bank(output, files, bank, clips):
    name = f"{bank}-{len(files)}.js"
    (output / name).write_text("export default " + json.dumps(clips, indent=2) + ";\n")
    files.append(name)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("model", type=Path, help="Path to ru_RU-denis-medium.onnx and its JSON")
    args = parser.parse_args()
    # No telemetry or remote inference. Set this before importing the runtime.
    os.environ["ORT_DISABLE_TELEMETRY"] = "1"
    from piper import PiperVoice
    from piper.config import SynthesisConfig

    plans = json.loads(subprocess.check_output(["node", "--input-type=module", "-e", """
import { FIRST_STEPS } from './assets/first-steps-data.js';
import { listeningClips } from './assets/listening-clips.js';
import { SOUND_PAIRS } from './assets/phonetics-content.js';
console.log(JSON.stringify({ FIRST_STEPS, listeningClips, SOUND_PAIRS }));
"""], cwd=ROOT, text=True))
    foundation = {
        ("letter-" + format(ord(s["model"]), "x") if s["kind"] == "letter" else s["id"]):
        LETTERS[s["model"]] if s["kind"] == "letter" else s["model"]
        for s in plans["FIRST_STEPS"] if s["kind"] != "review"
    }
    banks = {
        "foundation": foundation,
        "sounds": {f"{p['id']}-{i}": p[name]["ru"] for p in plans["SOUND_PAIRS"]
                   for i, name in enumerate(("a", "b"))},
        "listening": {c["id"]: c["russian"] for c in plans["listeningClips"]},
    }
    output = ROOT / "assets/audio"
    output.mkdir(parents=True, exist_ok=True)
    voice = PiperVoice.load(args.model)
    config = SynthesisConfig(length_scale=1.05, noise_scale=0.4, noise_w_scale=0.5)
    files = []
    with tempfile.TemporaryDirectory() as temp:
        wav_path = Path(temp) / "line.wav"
        for bank, items in banks.items():
            chunk = {}
            size = 0
            for name, line in items.items():
                with wave.open(str(wav_path), "wb") as wav:
                    voice.synthesize_wav(line, wav, syn_config=config)
                mp3 = subprocess.check_output([
                    "ffmpeg", "-nostdin", "-loglevel", "error", "-i", str(wav_path),
                    "-af", "apad=pad_dur=0.12", "-codec:a", "libmp3lame",
                    "-ar", "22050", "-ac", "1", "-b:a", "32k", "-f", "mp3", "pipe:1",
                ])
                value = b64encode(mp3).decode("ascii")
                if chunk and size + len(value) > 185000:
                    write_bank(output, files, bank, chunk)
                    chunk, size = {}, 0
                chunk[name] = value
                size += len(value)
            write_bank(output, files, bank, chunk)
            print(f"{bank}: {len(items)} clips", flush=True)
    names = ", ".join("bank" + str(i) for i in range(len(files)))
    imports = "".join(f'import bank{i} from "./{name}";\n' for i, name in enumerate(files))
    (output / "index.js").write_text(
        "// Generated by scripts/build-audio.py.\n" + imports +
        "export const audioClips = Object.assign(Object.create(null), " + names + ");\n"
    )
    (output / "cache-list.js").write_text(
        "// Generated by scripts/build-audio.py.\nconst AUDIO_FILES = " +
        json.dumps(["./assets/audio/index.js", *("./assets/audio/" + name for name in files)], indent=2) +
        ";\n"
    )

if __name__ == "__main__":
    main()
